import { describe, expect, it } from 'vitest';
import { breakSentences } from './breakSentences';

describe('breakSentences - 피보호자 말풍선 문장 줄바꿈', () => {
  it.each([
    [
      '여러 문장은 문장마다 줄을 바꾼다',
      '정형외과로 가시면 돼요. 가까운 정형외과를 찾아드릴게요. 어느 지역에서 찾을까요?',
      '정형외과로 가시면 돼요.\n가까운 정형외과를 찾아드릴게요.\n어느 지역에서 찾을까요?',
    ],
    ['숫자 사이 점은 끊지 않는다', '약은 1.5알씩 드세요. 식후에 드세요.', '약은 1.5알씩 드세요.\n식후에 드세요.'],
    ['번호 목록은 끊지 않는다', '1. 물을 드세요 2. 쉬세요', '1. 물을 드세요 2. 쉬세요'],
    [
      '날짜·시각은 끊지 않는다',
      '2026.11.04 오후 3:00에 예약했어요. 확인해 주세요!',
      '2026.11.04 오후 3:00에 예약했어요.\n확인해 주세요!',
    ],
    ['주소 번지는 끊지 않는다', '서울시 강남구 1.2번지예요. 맞나요?', '서울시 강남구 1.2번지예요.\n맞나요?'],
    [
      '괄호 안과 닫는 괄호 뒤는 끊지 않는다',
      '열이 나요(38도. 오늘 아침). 병원에 가세요.',
      '열이 나요(38도. 오늘 아침). 병원에 가세요.',
    ],
    [
      '이미 있는 줄바꿈은 그대로 두고 빈 줄을 만들지 않는다',
      '괜찮아요.\n다음은요? 알려 주세요.',
      '괜찮아요.\n다음은요?\n알려 주세요.',
    ],
    ['문장 끝 공백 뒤 줄바꿈도 그대로 둔다', '괜찮아요.  \n다음이에요.', '괜찮아요.  \n다음이에요.'],
    ['영어 약어는 끊지 않는다', 'Dr. Kim 선생님이에요. 내일 오세요.', 'Dr. Kim 선생님이에요.\n내일 오세요.'],
    ['다음 글자가 이모지면 끊지 않는다', '좋아요! 😊 또 물어보세요.', '좋아요! 😊 또 물어보세요.'],
    [
      '연속 문장 부호는 한 묶음으로 끊는다',
      '119에 바로 전화하세요!! 지금 위험할 수 있어요.',
      '119에 바로 전화하세요!!\n지금 위험할 수 있어요.',
    ],
    ['닫는 따옴표까지 붙여서 끊는다', '"괜찮아요." 라고 하셨죠? 네.', '"괜찮아요."\n라고 하셨죠?\n네.'],
    ['여러 칸 공백도 줄바꿈 하나로', '그래요.   다음이에요.', '그래요.\n다음이에요.'],
    ['공백 없이 붙은 점은 끊지 않는다', '그래요.다음이에요.', '그래요.다음이에요.'],
    ['한 문장은 그대로', '어디가 불편하세요?', '어디가 불편하세요?'],
    // 2026-11-05 점검 반영 (M-1·L-2)
    [
      '문장 뒤 괄호 보충 설명은 같은 줄에 둔다 (AI 되묻기 질문)',
      '· 얼마나 심하신가요? (참을 만한지, 점점 심해지는지)',
      '· 얼마나 심하신가요? (참을 만한지, 점점 심해지는지)',
    ],
    ['괄호 보충 뒤 다음 문장은 끊는다', '아파요. (어제부터) 그래요. 병원 가요.', '아파요. (어제부터) 그래요.\n병원 가요.'],
    ['대괄호 보충도 같은 줄에 둔다', '확인했어요. [예시] 예약돼요.', '확인했어요. [예시] 예약돼요.'],
    [
      '끝 공백은 줄바꿈으로 바꾸지 않는다 (예약 안내 답)',
      '내과로 가시면 돼요. 어느 지역에서 찾을까요? ',
      '내과로 가시면 돼요.\n어느 지역에서 찾을까요? ',
    ],
    ['CRLF 줄바꿈은 그대로 둔다', '괜찮아요. \r\n다음이에요. 네.', '괜찮아요. \r\n다음이에요.\n네.'],
    ['빈 문자열', '', ''],
  ])('%s', (_name, input, expected) => {
    expect(breakSentences(input)).toBe(expected);
  });

  it('원문 문자열을 바꾸지 않는다', () => {
    const original = '돼요. 찾을까요?';
    breakSentences(original);
    expect(original).toBe('돼요. 찾을까요?');
  });
});
