import type { Metadata } from 'next';
import localFont from 'next/font/local';
import './globals.css';
import ReactQueryProvider from '@/lib/ReactQueryProvider';
import PushNotificationListener from '@/components/PushNotificationListener';
import { ModalHost } from '@/components/ModalHost';
import { ToastHost } from '@/components/ToastHost';

// Pretendard Variable (SIL OFL 1.1, 라이선스: ./fonts/LICENSE-Pretendard.txt)
const pretendard = localFont({
  src: './fonts/PretendardVariable.woff2',
  variable: '--font-pretendard',
  weight: '45 920',
  display: 'swap',
  preload: true,
});

export const metadata: Metadata = {
  title: 'silver bridge',
  description: 'Generated by create next app',
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html suppressHydrationWarning className={pretendard.variable}>
      {/* CSS 변수뿐 아니라 next/font의 실제 family 클래스도 body에 적용한다.
          Windows·macOS에서 변수 전달 상태와 무관하게 로컬 Pretendard 파일을 우선 사용한다. */}
      <body className={pretendard.className}>
        <ReactQueryProvider>
          {children}
          <PushNotificationListener />
          <ModalHost />
          <ToastHost />
        </ReactQueryProvider>
      </body>
    </html>
  );
}
